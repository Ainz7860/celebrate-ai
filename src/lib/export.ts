import type { EventState, GeneratedPlan, EventRecord } from './types';
import { formatCurrency } from './budget';

/**
 * Exports the full event state as a formatted JSON string
 */
export function exportEventAsJson(state: EventState): string {
  return JSON.stringify(state, null, 2);
}

/**
 * Triggers a browser download of a text/JSON file
 */
export function downloadFile(content: string, filename: string, mimeType = 'application/json') {
  if (typeof window === 'undefined') return;
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

/**
 * Generates an executive Markdown summary of the event plan
 */
export function exportPlanAsMarkdown(event: EventRecord, plan: GeneratedPlan): string {
  const { budget, timeline, vendors, ideas } = plan;

  const lines: string[] = [];

  lines.push(`# ${event.name}`);
  lines.push(`**Type:** ${event.type.toUpperCase()} | **Date:** ${event.date} | **City:** ${event.city}`);
  lines.push(`**Guests:** ${event.guestCount} | **Budget:** ${formatCurrency(budget.totalBudget, budget.currency)}`);
  lines.push(`**Venue:** ${event.venueSetting} | **Generated by:** CelebrateAI (${plan.source})`);
  lines.push('\n---\n');

  lines.push('## Executive Summary');
  lines.push(plan.eventSummary);
  lines.push('');

  lines.push('## 💰 Budget Breakdown');
  lines.push(`- **Total Budget:** ${formatCurrency(budget.totalBudget, budget.currency)}`);
  lines.push(`- **Total Allocated:** ${formatCurrency(budget.totalAllocated, budget.currency)}`);
  lines.push(`- **Contingency Fund (${budget.contingencyPercent}%):** ${formatCurrency(budget.contingencyAmount, budget.currency)}`);
  lines.push(`- **Remaining Unallocated:** ${formatCurrency(budget.remaining, budget.currency)}`);
  lines.push('');
  lines.push('| Category | Allocated | Estimated | Notes |');
  lines.push('| :--- | :--- | :--- | :--- |');
  for (const cat of budget.categories) {
    lines.push(`| ${cat.name} | ${formatCurrency(cat.allocatedAmount, budget.currency)} | ${formatCurrency(cat.estimatedAmount, budget.currency)} | ${cat.notes || '-'} |`);
  }
  lines.push('');

  lines.push('## ⏱️ Timeline & Tasks');
  lines.push(`**Total Tasks:** ${timeline.totalCount} | **Completed:** ${timeline.completedCount}`);
  lines.push('');
  lines.push('| Deadline | Priority | Task | Category | Status |');
  lines.push('| :--- | :--- | :--- | :--- | :--- |');
  for (const t of timeline.tasks) {
    lines.push(`| ${t.deadline} | ${t.priority.toUpperCase()} | ${t.name} | ${t.category} | ${t.status} |`);
  }
  lines.push('');

  lines.push('## 🤝 Vendor Sourcing Guide');
  for (const v of vendors) {
    lines.push(`### ${v.vendorName || v.category.toUpperCase()} (${v.category})`);
    lines.push(`- **Status:** ${v.status} | **Est. Budget:** ${formatCurrency(v.estimatedBudget, budget.currency)}`);
    if (v.quotedPrice) lines.push(`- **Quoted Price:** ${formatCurrency(v.quotedPrice, budget.currency)}`);
    lines.push(`- **Requirements:** ${v.requirements}`);
    lines.push(`- **Key Questions to Ask:** ${v.questionsToAsk}`);
    lines.push(`- **Selection Criteria:** ${v.comparisonCriteria}`);
    lines.push('');
  }

  if (ideas && ideas.length > 0) {
    lines.push('## 💡 Creative Ideas & Themes');
    for (const idea of ideas) {
      lines.push(`- **${idea.title}** (${idea.category})`);
      lines.push(`  ${idea.description}`);
      if (idea.rationale) lines.push(`  *Rationale:* ${idea.rationale}`);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push(`*Generated on ${new Date(plan.generatedAt).toLocaleString()} with CelebrateAI.*`);

  return lines.join('\n');
}

/**
 * Triggers browser print dialog for the current event
 */
export function triggerPrintPlan() {
  if (typeof window !== 'undefined') {
    window.print();
  }
}
